using System.Text;
using XRay.Psd.Resources;
using XRay.Psd.Tests.Support;

namespace XRay.Psd.Tests;

public sealed class ResourceTests
{
    [Fact]
    public void Photoshop_resources_parse_into_typed_views()
    {
        var resources = Fixtures.Load("arrows.psd").Resources;

        Assert.Equal(new PsdResolutionInfo(72, PsdResolutionUnit.PixelsPerInch, PsdDimensionUnit.Inches, 72, PsdResolutionUnit.PixelsPerInch, PsdDimensionUnit.Inches), resources.Resolution);
        Assert.Equal(1.0, resources.PixelAspectRatio);
        Assert.Equal(new PsdPrintScale(PsdPrintScaleStyle.Centered, 0, 0, 1), resources.PrintScale);

        var grid = resources.GridAndGuides;
        Assert.NotNull(grid);
        Assert.Equal((18.0, 18.0), (grid.HorizontalGridCycle, grid.VerticalGridCycle));
        Assert.Empty(grid.Guides);

        var thumbnail = resources.Thumbnail;
        Assert.NotNull(thumbnail);
        Assert.Equal((PsdThumbnailFormat.Jpeg, 160, 114, 480, 24, false), (thumbnail.Format, thumbnail.Width, thumbnail.Height, thumbnail.RowBytes, thumbnail.BitsPerPixel, thumbnail.IsBgr));
        Assert.Equal(1692, thumbnail.Data.Length);
        Assert.True(thumbnail.Data.Span.StartsWith(new byte[] { 0xFF, 0xD8, 0xFF }));

        Assert.Equal(new PsdVersionInfo(1, true, "Adobe Photoshop", "Adobe Photoshop CS4", 1), resources.VersionInfo);

        var icc = resources.IccProfile;
        Assert.NotNull(icc);
        Assert.Equal(("sRGB IEC61966-2.1", "RGB ", "mntr", new Version(2, 1), 3144), (icc.Description, icc.ColorSpace, icc.DeviceClass, icc.Version, icc.Data.Length));

        var slices = resources.Slices;
        Assert.NotNull(slices);
        Assert.Equal((6, new PsdRect(0, 0, 486, 346), "arrows"), (slices.Version, slices.Bounds, slices.GroupName));
        var slice = Assert.Single(slices.Slices);
        Assert.Equal((PsdSliceOrigin.AutoGenerated, PsdSliceType.Image, new PsdRect(0, 0, 486, 346)), (slice.Origin, slice.Type, slice.Bounds));

        Assert.Equal(["Transparency"], resources.ChannelNames);
        Assert.Contains("x:xmpmeta", resources.Xmp, StringComparison.Ordinal);
        var iptc = Assert.Single(resources.Iptc);
        Assert.Equal((2, 0, 2), (iptc.Record, iptc.DataSet, iptc.Value.Length));
        Assert.Null(resources.LayerComps);
    }

    [Fact]
